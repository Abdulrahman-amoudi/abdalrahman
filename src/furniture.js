function ptext(x, str, px, py, col, s = 1) {
  x.fillStyle = col;
  [...str].forEach((ch, i) => { const g = FONT[ch] || FONT[' ']; for (let k = 0; k < 15; k++) if (g[k] === '1') x.fillRect(px + i * 4 * s + (k % 3) * s, py + Math.floor(k / 3) * s, s, s); });
}
